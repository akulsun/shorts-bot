"""Build ASS subtitle files from word-level timestamps.

The result is burned in by `render.py`; nothing here touches ffmpeg, so the
caption layout can be unit-tested with made-up words.
"""

from __future__ import annotations

from dataclasses import dataclass

from .config import Config
from .models import Clip, Transcript, Word

# Chunks are 2-4 words so they read like Shorts captions, not full sentences.
_MIN_WORDS_PER_CHUNK = 2
_BREAK_CHARS = (".", "!", "?", ",", ";", ":", "…")
# Keep a caption on screen briefly after the last word, but never overlap the
# next one (overlapping ASS events would draw on top of each other).
_HOLD_SECONDS = 0.15
_MIN_SHOW_SECONDS = 0.45
_MIN_EVENT_SECONDS = 0.08


@dataclass(frozen=True, slots=True)
class CaptionEvent:
    start: float
    end: float
    text: str


def build_events(
    transcript: Transcript, clip: Clip, max_words: int = 4
) -> list[CaptionEvent]:
    """Chunk the clip's words and return caption events in clip-relative time."""
    words = _clip_words(transcript, clip)
    if not words:
        return []

    chunks = _chunk_words(words, max_words)
    events: list[CaptionEvent] = []
    for position, chunk in enumerate(chunks):
        start = max(0.0, chunk[0].start - clip.start)
        end = min(clip.duration, chunk[-1].end - clip.start)
        end = min(clip.duration, max(end + _HOLD_SECONDS, start + _MIN_SHOW_SECONDS))

        if position + 1 < len(chunks):
            next_start = max(0.0, chunks[position + 1][0].start - clip.start)
            if end > next_start:
                end = next_start
        if end - start < _MIN_EVENT_SECONDS:
            end = min(clip.duration, start + _MIN_EVENT_SECONDS)
        if end <= start:
            continue

        text = _sanitize(" ".join(word.text.strip() for word in chunk))
        if text:
            events.append(CaptionEvent(round(start, 3), round(end, 3), text))
    return events


def build_ass(transcript: Transcript, clip: Clip, cfg: Config) -> str:
    """Render the clip's captions as a complete ASS document."""
    if not cfg.captions.enabled:
        return render_ass([], cfg)
    events = build_events(
        transcript, clip, max_words=cfg.captions.max_words_per_line
    )
    return render_ass(events, cfg)


def render_ass(events: list[CaptionEvent], cfg: Config) -> str:
    """Wrap caption events in the ASS header/style configured for the render."""
    captions = cfg.captions
    render = cfg.render
    bold = -1 if captions.bold else 0
    lines = [
        "[Script Info]",
        "; Generated by shorts-bot",
        "ScriptType: v4.00+",
        f"PlayResX: {render.width}",
        f"PlayResY: {render.height}",
        "WrapStyle: 0",
        "ScaledBorderAndShadow: yes",
        "",
        "[V4+ Styles]",
        (
            "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
            "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, "
            "ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
            "Alignment, MarginL, MarginR, MarginV, Encoding"
        ),
        (
            f"Style: Default,{captions.font},{captions.font_size},"
            f"&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,{bold},0,0,0,"
            f"100,100,0,0,1,{captions.outline},0,2,60,60,"
            f"{captions.margin_v},1"
        ),
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, "
        "Effect, Text",
    ]
    for event in events:
        lines.append(
            f"Dialogue: 0,{_ass_time(event.start)},{_ass_time(event.end)},"
            f"Default,,0,0,0,,{event.text}"
        )
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- #
# Chunking
# --------------------------------------------------------------------------- #


def _clip_words(transcript: Transcript, clip: Clip) -> list[Word]:
    return [
        word
        for word in transcript.words_between(clip.start, clip.end)
        if word.text.strip()
    ]


def _chunk_words(words: list[Word], max_words: int) -> list[list[Word]]:
    """Split into 2..max_words chunks, preferring punctuation boundaries."""
    max_words = max(_MIN_WORDS_PER_CHUNK, max_words)
    chunks: list[list[Word]] = []
    current: list[Word] = []

    for word in words:
        current.append(word)
        if len(current) >= max_words:
            chunks.append(current)
            current = []
        elif len(current) >= _MIN_WORDS_PER_CHUNK and word.text.rstrip().endswith(
            _BREAK_CHARS
        ):
            chunks.append(current)
            current = []

    # Never leave an orphan word: borrow one from the previous chunk, or merge.
    if len(current) == 1 and chunks:
        previous = chunks[-1]
        if len(previous) >= 3:
            current.insert(0, previous.pop())
        else:
            current = previous + current
            chunks.pop()
    if current:
        chunks.append(current)

    return chunks


# --------------------------------------------------------------------------- #
# Formatting
# --------------------------------------------------------------------------- #


def _ass_time(seconds: float) -> str:
    """ASS timestamps are H:MM:SS.cc (centiseconds)."""
    centis = max(0, int(round(seconds * 100)))
    hours, rest = divmod(centis, 360_000)
    minutes, rest = divmod(rest, 6_000)
    whole, centis = divmod(rest, 100)
    return f"{hours}:{minutes:02d}:{whole:02d}.{centis:02d}"


def _sanitize(text: str) -> str:
    """Remove characters that ASS would interpret as markup or line breaks."""
    text = " ".join(text.split())
    text = text.replace("\\", "")
    text = text.replace("{", "(").replace("}", ")")
    return text
